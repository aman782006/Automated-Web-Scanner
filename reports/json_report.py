"""
reports/json_report.py

Generates a structured JSON export for a completed scan.

The JSON report contains:
  - Scan metadata (ID, target, timestamp, status, elapsed time).
  - Executive summary (severity counts).
  - Detailed findings with evidence, remediation, and explanations.
  - Errors and limitations encountered during the scan.
  - A responsible-use disclaimer.

No credentials, cookies, or full response bodies are included.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from scanner.engine import ScanResult


DISCLAIMER = (
    "This report was generated by the Automated Web Security Scanner. "
    "Findings represent observations and potential risks identified through "
    "safe, non-intrusive HTTP analysis. They do not constitute confirmed "
    "exploitable vulnerabilities. Always verify findings in context before "
    "acting on them. Use this tool only against systems you are authorised "
    "to scan."
)

LIMITATIONS = [
    "Analysis is limited to HTTP response headers and does not assess application logic.",
    "CORS findings are based on header inspection, not active exploitation.",
    "TLS configuration depth (cipher suites, protocol versions) is not assessed.",
    "Authentication-protected resources are not analysed.",
    "Results reflect a single point-in-time snapshot.",
]


def generate_json_report(scan_result: "ScanResult") -> str:
    """
    Serialise *scan_result* into a JSON string suitable for download.

    Returns a valid UTF-8 JSON string.
    """
    data = {
        "report_metadata": {
            "tool": "Automated Web Security Scanner",
            "report_generated_at": datetime.now(timezone.utc).isoformat(),
            "scan_id": scan_result.scan_id,
        },
        "scan_metadata": {
            "target_url": scan_result.target_url,
            "scan_timestamp": scan_result.timestamp,
            "scan_status": scan_result.status,
            "http_status_code": scan_result.http_status,
            "elapsed_seconds": scan_result.elapsed_s,
        },
        "summary": {
            "total_findings": scan_result.summary.get("total", 0),
            "critical": scan_result.summary.get("critical", 0),
            "high": scan_result.summary.get("high", 0),
            "medium": scan_result.summary.get("medium", 0),
            "low": scan_result.summary.get("low", 0),
            "informational": scan_result.summary.get("informational", 0),
        },
        "findings": [f.to_dict() for f in scan_result.findings],
        "errors": scan_result.errors,
        "redirect_chain": scan_result.redirect_chain,
        "limitations": LIMITATIONS,
        "disclaimer": DISCLAIMER,
    }

    return json.dumps(data, indent=2, ensure_ascii=False)


def safe_filename(scan_id: str) -> str:
    """Return a safe download filename for the JSON report."""
    clean_id = "".join(c for c in scan_id if c.isalnum() or c in "-_")
    return f"scan_report_{clean_id[:36]}.json"
